//! Generated comment text (`##` blocks): wrapping and the brief / full renderings of the
//! metadata. Pure functions from metadata to lines; the writer decides where they go.

use audigma_settings::meta::{Field, SectionMeta};
use serde_json::Value;

/// Total line width including the `## ` prefix.
pub const WIDTH: usize = 80;
const PREFIX: &str = "## ";

/// How much commentary the writer generates.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum CommentLevel {
    /// No generated comments (existing `##` blocks are removed).
    None,
    /// One line per key and table.
    #[default]
    Brief,
    /// Summary, description, options and default.
    Full,
}

/// The first lines of a file, emitted unless the level is `None`.
pub fn notice() -> Vec<String> {
    wrap_comment(
        "Lines starting with `##` are generated by `audigma configure` and are rewritten on \
         every save. Use a single `#` for your own notes.",
    )
}

/// Comment lines (without the `## ` prefix; an empty string is a bare `##` line) for a key.
pub fn key_block(f: &Field, level: CommentLevel) -> Vec<String> {
    match level {
        CommentLevel::None => Vec::new(),
        CommentLevel::Brief => wrap_comment(&format!("{} {}", f.summary.trim(), brief_tail(f))),
        CommentLevel::Full => full_key(f),
    }
}

/// Comment lines for a `[section]` header.
pub fn section_block(s: &SectionMeta, level: CommentLevel) -> Vec<String> {
    summary_description(&s.summary, &s.description, level)
}

/// Comment lines for a `[section.group]` header.
pub fn group_block(f: &Field, level: CommentLevel) -> Vec<String> {
    summary_description(&f.summary, &f.description, level)
}

fn summary_description(summary: &str, description: &str, level: CommentLevel) -> Vec<String> {
    match level {
        CommentLevel::None => Vec::new(),
        CommentLevel::Brief => wrap_comment(summary.trim()),
        CommentLevel::Full => {
            let mut out = wrap_comment(summary.trim());
            if !description.trim().is_empty() {
                out.push(String::new());
                out.extend(markdown(description));
            }
            out
        }
    }
}

/// The text an option `key` is compared against (numbers by decimal text, like the loader).
pub fn option_text(v: &Value) -> Option<String> {
    match v {
        Value::String(s) => Some(s.clone()),
        Value::Bool(b) => Some(b.to_string()),
        Value::Number(n) => n.as_i64().map(|i| i.to_string()).or_else(|| {
            n.as_f64().map(|f| {
                if f.fract() == 0.0 {
                    format!("{}", f as i64)
                } else {
                    f.to_string()
                }
            })
        }),
        _ => None,
    }
}

/// A value as shown in comments: strings bare, arrays as `[a, b]`.
pub fn show_value(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Array(a) => format!(
            "[{}]",
            a.iter().map(show_value).collect::<Vec<_>>().join(", ")
        ),
        other => other.to_string(),
    }
}

fn show_num(x: f64) -> String {
    if x.fract() == 0.0 {
        format!("{}", x as i64)
    } else {
        x.to_string()
    }
}

fn range_text(f: &Field) -> Option<String> {
    f.range
        .map(|[lo, hi]| format!("Range: {} to {}.", show_num(lo), show_num(hi)))
}

fn integer_text(i: &audigma_settings::meta::IntegerOption) -> String {
    format!("a whole number from {} to {}", i.range[0], i.range[1])
}

fn default_option_index(f: &Field) -> Option<usize> {
    let d = option_text(f.default.as_ref()?)?;
    f.options.iter().position(|o| o.key == d)
}

/// `Values: a (default), b.` / `Default: 5. Range: 1 to 9.` (generated, not stored).
fn brief_tail(f: &Field) -> String {
    let mut parts = Vec::new();
    let default_in_options = default_option_index(f);
    if !f.options.is_empty() {
        let mut items: Vec<String> = f
            .options
            .iter()
            .enumerate()
            .map(|(i, o)| {
                if Some(i) == default_in_options {
                    format!("{} (default)", o.key)
                } else {
                    o.key.clone()
                }
            })
            .collect();
        if let Some(i) = &f.also_integer {
            items.push(format!("or {}", integer_text(i)));
        }
        parts.push(format!("Values: {}.", items.join(", ")));
    }
    if default_in_options.is_none() {
        if let Some(d) = &f.default {
            parts.push(format!("Default: {}.", show_value(d)));
        } else if let Some(t) = &f.default_text {
            parts.push(format!("Default: {}", with_period(t)));
        }
    }
    if let Some(r) = range_text(f) {
        parts.push(r);
    }
    parts.join(" ")
}

fn with_period(s: &str) -> String {
    let s = s.trim();
    if s.ends_with(['.', '!', '?']) {
        s.to_string()
    } else {
        format!("{s}.")
    }
}

fn full_key(f: &Field) -> Vec<String> {
    let mut out = wrap_comment(f.summary.trim());
    if !f.description.trim().is_empty() {
        out.push(String::new());
        out.extend(markdown(&f.description));
    }
    let mut bullets: Vec<String> = f
        .options
        .iter()
        .map(|o| {
            let body = if o.description.trim().is_empty() {
                o.summary.as_str()
            } else {
                o.description.as_str()
            };
            let mut t = format!("- `{}`: {}", o.key, collapse(body));
            if let Some(c) = &o.caution {
                t.push_str(&format!(" Caution: {}", collapse(c)));
            }
            t
        })
        .collect();
    if let Some(i) = &f.also_integer {
        let body = if i.description.trim().is_empty() {
            i.summary.as_str()
        } else {
            i.description.as_str()
        };
        bullets.push(format!(
            "- {}: {}",
            capitalize(&integer_text(i)),
            collapse(body)
        ));
    }
    if !bullets.is_empty() {
        out.push(String::new());
        for b in bullets {
            out.extend(wrap(&b, "", "  "));
        }
    }
    let mut tail = Vec::new();
    if let Some(d) = &f.default {
        tail.push(format!("Default: `{}`.", show_value(d)));
    } else if let Some(t) = &f.default_text {
        tail.push(format!("Default: {}", with_period(t)));
    }
    if let Some(r) = range_text(f) {
        tail.push(r);
    }
    if !tail.is_empty() {
        out.push(String::new());
        out.extend(wrap(&tail.join(" "), "", ""));
    }
    out
}

fn capitalize(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(first) => first.to_uppercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}

fn collapse(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn wrap_comment(text: &str) -> Vec<String> {
    wrap(&collapse(text), "", "")
}

/// Renders the markdown subset (paragraphs, `- ` bullets, code spans) as wrapped lines.
pub fn markdown(text: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for para in text.trim().split("\n\n") {
        // Units of this paragraph: (is_bullet, text)
        let mut units: Vec<(bool, String)> = Vec::new();
        for line in para.lines() {
            let t = line.trim();
            if t.is_empty() {
                continue;
            }
            if let Some(item) = t.strip_prefix("- ") {
                units.push((true, item.trim().to_string()));
            } else if let Some(last) = units.last_mut() {
                last.1.push(' ');
                last.1.push_str(t);
            } else {
                units.push((false, t.to_string()));
            }
        }
        if units.is_empty() {
            continue;
        }
        if !out.is_empty() {
            out.push(String::new());
        }
        for (bullet, body) in units {
            if bullet {
                out.extend(wrap(&format!("- {body}"), "", "  "));
            } else {
                out.extend(wrap(&body, "", ""));
            }
        }
    }
    out
}

/// Splits on whitespace but keeps backtick spans whole.
fn words(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut in_code = false;
    for ch in s.chars() {
        match ch {
            '`' => {
                in_code = !in_code;
                cur.push(ch);
            }
            c if c.is_whitespace() && !in_code => {
                if !cur.is_empty() {
                    out.push(std::mem::take(&mut cur));
                }
            }
            c => cur.push(c),
        }
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

/// Greedy wrap to the content width (`WIDTH` minus the `## ` prefix). `first` / `rest` are the
/// indents of the first and following lines; a bullet hangs by passing `rest = "  "`.
fn wrap(text: &str, first: &str, rest: &str) -> Vec<String> {
    let width = WIDTH - PREFIX.len();
    let mut lines = Vec::new();
    let mut line = String::from(first);
    let mut empty = true;
    for w in words(text) {
        let w_len = w.chars().count();
        if !empty && line.chars().count() + 1 + w_len > width {
            lines.push(std::mem::take(&mut line));
            line.push_str(rest);
            empty = true;
        }
        if !empty {
            line.push(' ');
        }
        line.push_str(&w);
        empty = false;
    }
    if !empty {
        lines.push(line);
    }
    lines
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn wrap_keeps_code_spans_whole_and_hangs_bullets() {
        let lines = markdown(
            "- `a b c` aaaaaaaaaa bbbbbbbbbb cccccccccc dddddddddd eeeeeeeeee ffffffffff gggggggggg hhhhhhhhhh",
        );
        assert!(lines.iter().all(|l| l.chars().count() <= WIDTH - 3));
        assert!(lines[0].starts_with("- `a b c`"));
        assert!(lines[1].starts_with("  "));
    }

    #[test]
    fn paragraphs_are_separated_by_an_empty_line() {
        assert_eq!(markdown("one\ntwo\n\nthree"), vec!["one two", "", "three"]);
    }

    #[test]
    fn overlong_word_stays_on_its_own_line() {
        let long = "x".repeat(100);
        let lines = wrap(&format!("a {long} b"), "", "");
        assert_eq!(lines, vec!["a".to_string(), long, "b".to_string()]);
    }
}
