// Generates src/generated/types.ts and zod.ts from the two JSON Schemas that
// `cargo run -p audigma-configurator --example gen_schema` writes next to them.
// Output must be deterministic: the Rust drift test regenerates and compares.
import { compile } from "json-schema-to-typescript";
import { jsonSchemaToZod } from "json-schema-to-zod";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Optional argument: another directory holding the two schemas (the Rust drift test uses this).
const dir =
  process.argv[2] ?? join(dirname(fileURLToPath(import.meta.url)), "..", "src", "generated");
const inputs = [
  { file: "settings.schema.json", name: "Settings" },
  { file: "meta.schema.json", name: "MetaBundle" },
] as const;

type Json = null | boolean | number | string | Json[] | { [k: string]: Json };

// json-schema-to-zod does not follow `$ref`, so inline every local reference. A reference that
// points back into itself (`Condition` nests `Condition`) becomes an empty schema (`any`): the
// frontends evaluate conditions in code and do not rely on zod for that shape.
function inline(node: Json, root: { [k: string]: Json }, stack: string[] = []): Json {
  if (Array.isArray(node)) return node.map((n) => inline(n, root, stack));
  if (node === null || typeof node !== "object") return node;
  const ref = node["$ref"];
  if (typeof ref === "string") {
    if (!ref.startsWith("#/")) throw new Error(`unsupported $ref ${ref}`);
    if (stack.includes(ref)) return {};
    let target: Json = root;
    for (const part of ref.slice(2).split("/")) target = (target as { [k: string]: Json })[part];
    return inline(target, root, [...stack, ref]);
  }
  const out: { [k: string]: Json } = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "$defs" || k === "$schema") continue;
    out[k] = inline(v, root, stack);
  }
  return out;
}

const banner =
  "// GENERATED by `cargo run -p audigma-configurator --example gen_schema`. Do not edit.\n";

let types = banner;
let zod = banner + 'import { z } from "zod";\n';
for (const { file, name } of inputs) {
  const schema = JSON.parse(readFileSync(join(dir, file), "utf8"));
  types += "\n" + (await compile(schema, name, { bannerComment: "", additionalProperties: false, format: false }));
  zod +=
    `\nexport const ${name}Schema = ` +
    jsonSchemaToZod(inline(schema, schema) as object, { module: "none", name: undefined, type: false }) +
    ";\n";
}
writeFileSync(join(dir, "types.ts"), types);
writeFileSync(join(dir, "zod.ts"), zod);
