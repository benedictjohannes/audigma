//! The committed `web/src/generated/*` files must equal what the Rust types produce.
//! Fix a failure with `cargo run -p audigma-configurator --example gen_schema`.

use std::path::{Path, PathBuf};
use std::process::Command;

fn web() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("web")
}

fn generated() -> PathBuf {
    web().join("src/generated")
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

#[test]
fn json_schemas_match_committed_files() {
    for (name, expected) in audigma_configurator::schema::generated_files() {
        assert!(
            read(&generated().join(name)) == expected,
            "{name} is stale: run `cargo run -p audigma-configurator --example gen_schema`"
        );
    }
}

/// `types.ts` and `zod.ts` are generated by bun from the schemas. Skipped (with a note) when bun
/// or `bun install` is missing, unless `AUDIGMA_REQUIRE_BUN` is set.
#[test]
fn typescript_outputs_match_committed_files() {
    let have_bun = Command::new("bun").arg("--version").output().is_ok()
        && web().join("node_modules").is_dir();
    if !have_bun {
        assert!(
            std::env::var_os("AUDIGMA_REQUIRE_BUN").is_none(),
            "bun or web/node_modules missing"
        );
        eprintln!("skipped: bun or web/node_modules missing (run `bun install` in web/)");
        return;
    }
    let tmp = tempfile::tempdir().unwrap();
    for (name, text) in audigma_configurator::schema::generated_files() {
        std::fs::write(tmp.path().join(name), text).unwrap();
    }
    let status = Command::new("bun")
        .arg(web().join("scripts/gen.ts"))
        .arg(tmp.path())
        .current_dir(web())
        .status()
        .unwrap();
    assert!(status.success(), "bun scripts/gen.ts failed");
    for name in ["types.ts", "zod.ts"] {
        assert!(
            read(&tmp.path().join(name)) == read(&generated().join(name)),
            "{name} is stale: run `cargo run -p audigma-configurator --example gen_schema`"
        );
    }
}

#[test]
fn meta_json_matches_its_schema_shape() {
    let meta = audigma_configurator::schema::meta_json();
    let sections = meta["sections"].as_array().unwrap();
    assert_eq!(sections.len(), 8);
    assert_eq!(sections[0]["name"], "input");
    assert!(sections[0]["fields"].as_array().unwrap().len() > 5);
    assert!(
        meta["assists"]
            .as_array()
            .unwrap()
            .iter()
            .any(|a| a["id"] == "quality-starting-point")
    );
}
