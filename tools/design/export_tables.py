from pathlib import Path
import numpy as np

from design_halfband import design_all
from design_src import design_src
from design_crfb import synthesize_crfb


def format_f64_array(arr, indent=4, per_line=4):
    lines = []
    curr = []
    ind = " " * indent
    for val in arr:
        curr.append(f"{val:22.17e}")
        if len(curr) == per_line:
            lines.append(ind + ", ".join(curr) + ",")
            curr = []
    if curr:
        lines.append(ind + ", ".join(curr) + ",")
    return "\n".join(lines)


def generate_tables_rs(halfband, src, crfb5_rates, crfb7_rates):
    code = []
    code.append("//! Static verified filter and modulator coefficient tables (Design.md §4.2, §4.3).")
    code.append("//! Automatically generated by `tools/design/export_tables.py`.")
    code.append("//! Zero heap allocation, fully reproducible from scipy/numpy design oracles.\n")
    code.append("#![allow(clippy::excessive_precision, clippy::approx_constant)]\n")
    code.append("use crate::config::{Apodization, FilterPhase};")
    code.append("use crate::rates::DsdBitRateHz;\n")

    # CRFB Coefficients Structs
    code.append("/// Static 5th-order CRFB Delta-Sigma Modulator coefficient set (Design.md §4.3).")
    code.append("#[derive(Debug, Clone, Copy, PartialEq)]")
    code.append("pub struct CrfbCoefficients {")
    code.append("    /// First resonator local feedback coupling g1.")
    code.append("    pub g1: f64,")
    code.append("    /// Second resonator local feedback coupling g2.")
    code.append("    pub g2: f64,")
    code.append("    /// Quantizer DAC feedback gains a1..a5.")
    code.append("    pub a: [f64; 5],")
    code.append("    /// Input feed-in gain b1 calibrated for exact unity DC STF gain.")
    code.append("    pub b1: f64,")
    code.append("    /// Out-of-band NTF gain the loop was synthesised for (`design_crfb.py`).")
    code.append("    pub ntf_h_inf: f64,")
    code.append("    /// Measured maximum stable input `L` in dBFS (DC + tone sweep, `design_crfb.measure_msa_dbfs`).")
    code.append("    pub max_stable_input_dbfs: f64,")
    code.append("}\n")
    code.append("/// Alias for 5th-order CRFB coefficients.")
    code.append("pub type CrfbCoefficients5 = CrfbCoefficients;\n")

    code.append("/// Static 7th-order CRFB Delta-Sigma Modulator coefficient set (Design.md §4.3).")
    code.append("#[derive(Debug, Clone, Copy, PartialEq)]")
    code.append("pub struct CrfbCoefficients7 {")
    code.append("    /// First resonator local feedback coupling g1.")
    code.append("    pub g1: f64,")
    code.append("    /// Second resonator local feedback coupling g2.")
    code.append("    pub g2: f64,")
    code.append("    /// Third resonator local feedback coupling g3.")
    code.append("    pub g3: f64,")
    code.append("    /// Quantizer DAC feedback gains a1..a7.")
    code.append("    pub a: [f64; 7],")
    code.append("    /// Input feed-in gain b1 calibrated for exact unity DC STF gain.")
    code.append("    pub b1: f64,")
    code.append("    /// Out-of-band NTF gain the loop was synthesised for (`design_crfb.py`).")
    code.append("    pub ntf_h_inf: f64,")
    code.append("    /// Measured maximum stable input `L` in dBFS (DC + tone sweep, `design_crfb.measure_msa_dbfs`).")
    code.append("    pub max_stable_input_dbfs: f64,")
    code.append("}\n")

    # Export 5th-order CRFB tables
    for item in crfb5_rates:
        name = item["name"].upper()
        g1 = item["g1"]
        g2 = item["g2"]
        b1 = item["b1"]
        a_formatted = ", ".join(f"{v:.17e}" for v in item["a"])
        code.append(f"/// 5th-order CRFB coefficients for {item['name']} (f_bit={item['f_bit_hz']} Hz, OSR={item['osr']:.2f}).")
        code.append(f"pub const CRFB5_{name}: CrfbCoefficients5 = CrfbCoefficients5 {{")
        code.append(f"    g1: {g1:.17e},")
        code.append(f"    g2: {g2:.17e},")
        code.append(f"    a: [{a_formatted}],")
        code.append(f"    b1: {b1:.17e},")
        code.append(f"    ntf_h_inf: {item['H_inf']!r},")
        code.append(f"    max_stable_input_dbfs: {item['stable_msa_dbfs']!r},")
        code.append("};\n")
        code.append(f"/// Backward-compatible alias for 5th-order {name} coefficients.")
        code.append(f"pub const CRFB_{name}: CrfbCoefficients = CRFB5_{name};\n")

    # Export 7th-order CRFB tables
    for item in crfb7_rates:
        name = item["name"].upper()
        g1 = item["g1"]
        g2 = item["g2"]
        g3 = item["g3"]
        b1 = item["b1"]
        a_formatted = ", ".join(f"{v:.17e}" for v in item["a"])
        code.append(f"/// 7th-order CRFB coefficients for {item['name']} (f_bit={item['f_bit_hz']} Hz, OSR={item['osr']:.2f}).")
        code.append(f"pub const CRFB7_{name}: CrfbCoefficients7 = CrfbCoefficients7 {{")
        code.append(f"    g1: {g1:.17e},")
        code.append(f"    g2: {g2:.17e},")
        code.append(f"    g3: {g3:.17e},")
        code.append(f"    a: [{a_formatted}],")
        code.append(f"    b1: {b1:.17e},")
        code.append(f"    ntf_h_inf: {item['H_inf']!r},")
        code.append(f"    max_stable_input_dbfs: {item['stable_msa_dbfs']!r},")
        code.append("};\n")

    # CRFB lookup functions
    code.append("/// Looks up the precomputed 5th-order CRFB coefficients for a given DSD bit rate (backward-compatible).")
    code.append("pub fn get_crfb_coefficients(bit_rate: DsdBitRateHz) -> Option<&'static CrfbCoefficients> {")
    code.append("    get_crfb5_coefficients(bit_rate)")
    code.append("}\n")

    code.append("/// Looks up the precomputed 5th-order CRFB coefficients for a given DSD bit rate.")
    code.append("pub fn get_crfb5_coefficients(bit_rate: DsdBitRateHz) -> Option<&'static CrfbCoefficients5> {")
    code.append("    match bit_rate {")
    for item in crfb5_rates:
        name = item["name"].upper()
        if name.endswith("_48"):
            base = name.replace("_48", "")
            code.append(f"        DsdBitRateHz::{base}_48 => Some(&CRFB5_{name}),")
        else:
            code.append(f"        DsdBitRateHz::{name} => Some(&CRFB5_{name}),")
    code.append("        _ => None,")
    code.append("    }")
    code.append("}\n")

    code.append("/// Looks up the precomputed 7th-order CRFB coefficients for a given DSD bit rate.")
    code.append("pub fn get_crfb7_coefficients(bit_rate: DsdBitRateHz) -> Option<&'static CrfbCoefficients7> {")
    code.append("    match bit_rate {")
    for item in crfb7_rates:
        name = item["name"].upper()
        if name.endswith("_48"):
            base = name.replace("_48", "")
            code.append(f"        DsdBitRateHz::{base}_48 => Some(&CRFB7_{name}),")
        else:
            code.append(f"        DsdBitRateHz::{name} => Some(&CRFB7_{name}),")
    code.append("        _ => None,")
    code.append("    }")
    code.append("}\n")

    # Half-band stages: symmetric odd taps (linear phase) and full minimum-phase taps per stage index.
    stages = halfband["halfband"]
    code.append("/// Number of 2x stages with their own half-band design (44.1 kHz -> DSD512 is 9 stages).")
    code.append(f"pub const HALFBAND_MAX_STAGES: usize = {len(stages)};\n")
    for k, modes in enumerate(stages):
        lin = modes["linear"]
        mn = modes["minimum"]
        taps = lin["unique_odd_taps"]
        code.append(
            f"/// Half-band stage {k} unique odd taps (linear phase; {lin['numtaps']} taps, pass 20 kHz, "
            f"stop {lin['stopband_hz'] / 1e3:.1f} kHz at {lin['fs_hz'] / 1e3:.1f} kHz, rejection {lin['sb_rejection_db']:.1f} dB)."
        )
        code.append(f"pub const HALFBAND_STAGE{k}_ODD_TAPS: [f64; {len(taps)}] = [")
        code.append(format_f64_array(taps, indent=4))
        code.append("];\n")
        code.append(
            f"/// Half-band stage {k} full taps (minimum phase; {mn['numtaps']} taps, rejection {mn['sb_rejection_db']:.1f} dB)."
        )
        code.append(f"pub const HALFBAND_STAGE{k}_MINIMUM_TAPS: [f64; {len(mn['full_taps'])}] = [")
        code.append(format_f64_array(mn["full_taps"], indent=4))
        code.append("];\n")

    # Apodizing stage-0 filters per pass edge and phase.
    apod = halfband["apodizing"]
    for edge, modes in apod.items():
        for phase_key, suffix in (("linear", "LINEAR"), ("minimum", "MINIMUM")):
            rec = modes[phase_key]
            code.append(
                f"/// Apodizing stage 0, pass edge {edge} Hz ({phase_key} phase; {rec['numtaps']} taps, "
                f"stop 22.05 kHz, rejection {rec['sb_rejection_db']:.1f} dB)."
            )
            code.append(f"pub const APODIZING_{edge}_{suffix}_TAPS: [f64; {len(rec['full_taps'])}] = [")
            code.append(format_f64_array(rec["full_taps"], indent=4))
            code.append("];\n")

    code.append("/// Stage filter coefficients selected by phase and apodization.")
    code.append("#[derive(Debug, Clone, Copy, PartialEq)]")
    code.append("pub enum HalfBandTaps {")
    code.append("    /// Symmetric half-band prototype stored as unique positive odd taps.")
    code.append("    Symmetric(&'static [f64]),")
    code.append("    /// General full-length FIR prototype stored as all taps.")
    code.append("    General(&'static [f64]),")
    code.append("}\n")

    code.append("/// Linear-phase half-band odd taps of 2x stage `stage` (interpolation stage index, or the decimator's")
    code.append("/// stage counted back from its output). Stages beyond the table reuse the last (most relaxed) design.")
    code.append("pub fn get_halfband_odd_taps(stage: usize) -> &'static [f64] {")
    code.append("    match stage {")
    for k in range(len(stages)):
        arm = f"{k}" if k < len(stages) - 1 else "_"
        code.append(f"        {arm} => &HALFBAND_STAGE{k}_ODD_TAPS,")
    code.append("    }")
    code.append("}\n")

    code.append("/// Minimum-phase half-band taps of 2x stage `stage` (same stage rule as `get_halfband_odd_taps`).")
    code.append("pub fn get_halfband_minimum_taps(stage: usize) -> &'static [f64] {")
    code.append("    match stage {")
    for k in range(len(stages)):
        arm = f"{k}" if k < len(stages) - 1 else "_"
        code.append(f"        {arm} => &HALFBAND_STAGE{k}_MINIMUM_TAPS,")
    code.append("    }")
    code.append("}\n")

    code.append("/// Returns the filter of 2x interpolation stage `stage`. Apodization only affects stage 0.")
    code.append("pub fn get_interpolation_stage_filter(")
    code.append("    stage: usize,")
    code.append("    phase: FilterPhase,")
    code.append("    apodization: Apodization,")
    code.append(") -> HalfBandTaps {")
    code.append("    if stage == 0 {")
    code.append("        let apodizing: Option<&'static [f64]> = match (apodization, phase) {")
    code.append("            (Apodization::Off, _) => None,")
    for edge in apod:
        for ph, suffix in (("Linear", "LINEAR"), ("Minimum", "MINIMUM")):
            code.append(f"            (Apodization::PassEdge{edge}, FilterPhase::{ph}) => Some(&APODIZING_{edge}_{suffix}_TAPS),")
    code.append("        };")
    code.append("        if let Some(taps) = apodizing {")
    code.append("            return HalfBandTaps::General(taps);")
    code.append("        }")
    code.append("    }")
    code.append("    match phase {")
    code.append("        FilterPhase::Linear => HalfBandTaps::Symmetric(get_halfband_odd_taps(stage)),")
    code.append("        FilterPhase::Minimum => HalfBandTaps::General(get_halfband_minimum_taps(stage)),")
    code.append("    }")
    code.append("}\n")

    # Export the polyphase SRC design parameters; the banks are built from the closed-form
    # prototype when a resampler is constructed (tools/design/design_src.py, fir::src_prototype).
    code.append("/// SRC prototype cutoff, as a fraction of the lower of the two rates (Design.md §4.2, `design_src.py`).")
    code.append(f"pub const SRC_CUTOFF: f64 = {src['cutoff']!r};")
    code.append(f"/// SRC passband edge (20 kHz at 44.1 kHz), as a fraction of the lower rate.")
    code.append(f"pub const SRC_PASS_EDGE: f64 = {src['pass_edge']!r};")
    code.append(f"/// SRC stopband edge (24.1 kHz at 44.1 kHz), as a fraction of the lower rate.")
    code.append(f"pub const SRC_STOP_EDGE: f64 = {src['stop_edge']!r};")
    code.append(f"/// Kaiser window beta of the SRC prototype ({src['atten_db']:.0f} dB design attenuation).")
    code.append(f"pub const SRC_KAISER_BETA: f64 = {src['beta']!r};")
    code.append(
        f"/// SRC taps per output sample when no downsampling is involved (measured prototype: "
        f"passband deviation {src['passband_dev_db']:.1e} dB, rejection {src['stopband_rejection_db']:.1f} dB)."
    )
    code.append(f"pub const SRC_TAPS_UNITY: usize = {src['taps_unity']};")
    code.append("/// Phases of the ASRC bank; positions between phases are cubic (4-point Lagrange) interpolated.")
    code.append(f"pub const SRC_ASRC_PHASES: usize = {src['asrc_phases']};\n")

    code.append("""#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_crfb_coefficient_lookups() {
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD64).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD128).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD256).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD512).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD64_48).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD128_48).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD256_48).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD512_48).is_some());

        let dsd256 = get_crfb_coefficients(DsdBitRateHz::DSD256).unwrap();
        assert!(dsd256.g1 > 0.0);
        assert!(dsd256.g2 > 0.0);
        assert!(dsd256.b1 > 0.0);
        assert_eq!(dsd256.a.len(), 5);
        for &a_val in &dsd256.a {
            assert!(a_val > 0.0);
        }

        let dsd512 = get_crfb_coefficients(DsdBitRateHz::DSD512).unwrap();
        assert!(dsd512.g1 > 0.0);
        assert!(dsd512.g2 > 0.0);
        assert!(dsd512.b1 > 0.0);
        assert_eq!(dsd512.a.len(), 5);
        for &a_val in &dsd512.a {
            assert!(a_val > 0.0);
        }

        assert!(get_crfb7_coefficients(DsdBitRateHz::DSD64).is_some());
        assert!(get_crfb7_coefficients(DsdBitRateHz::DSD128).is_some());
        assert!(get_crfb7_coefficients(DsdBitRateHz::DSD256).is_some());
        assert!(get_crfb7_coefficients(DsdBitRateHz::DSD512).is_some());
        assert!(get_crfb7_coefficients(DsdBitRateHz::DSD64_48).is_some());
        assert!(get_crfb7_coefficients(DsdBitRateHz::DSD128_48).is_some());
        assert!(get_crfb7_coefficients(DsdBitRateHz::DSD256_48).is_some());
        assert!(get_crfb7_coefficients(DsdBitRateHz::DSD512_48).is_some());

        let dsd256_7 = get_crfb7_coefficients(DsdBitRateHz::DSD256).unwrap();
        assert!(dsd256_7.g1 > 0.0);
        assert!(dsd256_7.g2 > 0.0);
        assert!(dsd256_7.g3 > 0.0);
        assert!(dsd256_7.b1 > 0.0);
        assert_eq!(dsd256_7.a.len(), 7);
        for &a_val in &dsd256_7.a {
            assert!(a_val > 0.0);
        }

        let dsd512_7 = get_crfb7_coefficients(DsdBitRateHz::DSD512).unwrap();
        assert!(dsd512_7.g1 > 0.0);
        assert!(dsd512_7.g2 > 0.0);
        assert!(dsd512_7.g3 > 0.0);
        assert!(dsd512_7.b1 > 0.0);
        assert_eq!(dsd512_7.a.len(), 7);
        for &a_val in &dsd512_7.a {
            assert!(a_val > 0.0);
        }
    }

    #[test]
    fn test_halfband_stage_lengths_and_dc() {
        // Full lengths 199/31/19/15/11/11/7/7/7 -> (N + 1) / 4 unique odd taps.
        let expected = [50usize, 8, 5, 4, 3, 3, 2, 2, 2];
        assert_eq!(HALFBAND_MAX_STAGES, expected.len());
        for (stage, &len) in expected.iter().enumerate() {
            let odd = get_halfband_odd_taps(stage);
            assert_eq!(odd.len(), len, "stage {stage}");
            // The 0.5 centre tap plus both mirrored odd halves give unity DC.
            assert!((odd.iter().sum::<f64>() * 2.0 - 0.5).abs() < 1e-12, "stage {stage}");
            let minimum = get_halfband_minimum_taps(stage);
            assert_eq!(minimum.len(), 4 * len - 1, "stage {stage}");
            assert!((minimum.iter().sum::<f64>() - 1.0).abs() < 1e-12, "stage {stage}");
        }
        // Stages past the table reuse the last design.
        assert_eq!(
            get_halfband_odd_taps(HALFBAND_MAX_STAGES),
            get_halfband_odd_taps(HALFBAND_MAX_STAGES - 1)
        );
    }

    fn general_taps(taps: HalfBandTaps) -> &'static [f64] {
        match taps {
            HalfBandTaps::General(taps) => taps,
            HalfBandTaps::Symmetric(_) => panic!("expected general full-length taps"),
        }
    }

    #[test]
    fn test_interpolation_filter_matrix() {
        use FilterPhase::{Linear, Minimum};

        assert!(matches!(
            get_interpolation_stage_filter(0, Linear, Apodization::Off),
            HalfBandTaps::Symmetric(_)
        ));
        assert_eq!(
            general_taps(get_interpolation_stage_filter(0, Minimum, Apodization::Off)).len(),
            199
        );

        let expected = [
            (Apodization::PassEdge18000, 209usize),
            (Apodization::PassEdge18500, 237),
            (Apodization::PassEdge19000, 277),
            (Apodization::PassEdge20000, 409),
        ];
        for (apodization, len) in expected {
            for phase in [Linear, Minimum] {
                let taps = general_taps(get_interpolation_stage_filter(0, phase, apodization));
                assert_eq!(taps.len(), len, "{apodization:?}/{phase:?}");
                assert!((taps.iter().sum::<f64>() - 1.0).abs() < 1e-12);
            }
            // Apodization only affects stage 0.
            assert_eq!(
                get_interpolation_stage_filter(1, Linear, apodization),
                get_interpolation_stage_filter(1, Linear, Apodization::Off)
            );
        }
        assert_eq!(
            get_interpolation_stage_filter(3, Linear, Apodization::Off),
            HalfBandTaps::Symmetric(&HALFBAND_STAGE3_ODD_TAPS)
        );
        assert_eq!(
            get_interpolation_stage_filter(3, Minimum, Apodization::Off),
            HalfBandTaps::General(&HALFBAND_STAGE3_MINIMUM_TAPS)
        );
    }
}
""")

    return "\n".join(code)


def main():
    print("Synthesizing Half-Band Filters...")
    halfband = design_all()

    print("Designing the polyphase SRC prototype...")
    src = design_src()

    rate_tuples = [
        ("DSD64", 2822400),
        ("DSD128", 5644800),
        ("DSD256", 11289600),
        ("DSD512", 22579200),
        ("DSD64_48", 3072000),
        ("DSD128_48", 6144000),
        ("DSD256_48", 12288000),
        ("DSD512_48", 24576000),
    ]

    print("Synthesizing 5th-Order CRFB Modulator Coefficients...")
    crfb5_rates = []
    for name, f_bit in rate_tuples:
        crfb5_rates.append(synthesize_crfb(f_bit, order=5, H_inf=1.40, name=name, sweep_msa=True))

    print("Synthesizing 7th-Order CRFB Modulator Coefficients...")
    crfb7_rates = []
    for name, f_bit in rate_tuples:
        crfb7_rates.append(synthesize_crfb(f_bit, order=7, H_inf=1.40, name=name, sweep_msa=True))

    code = generate_tables_rs(halfband, src, crfb5_rates, crfb7_rates)

    out_path = Path(__file__).resolve().parents[2] / "crates" / "audigma-dsp" / "src" / "tables.rs"
    out_path.write_text(code)
    print(f"Successfully generated {out_path} ({len(code)} bytes)")


if __name__ == "__main__":
    main()
