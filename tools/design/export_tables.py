    code.append("pub fn get_halfband_stage1_filter(\n    preset: FilterPreset,\n    phase: FilterPhase,\n) -> HalfBandTaps {")
    code.append("    match phase {")
    code.append("        FilterPhase::Linear => HalfBandTaps::Symmetric(get_halfband_stage1_taps(preset)),")
    code.append(
        "        FilterPhase::Minimum => HalfBandTaps::General(match preset {"
    )
    code.append("            FilterPreset::Balanced => &HALFBAND_STAGE1_BALANCED_MINIMUM_OFF_TAPS,")
    code.append("            FilterPreset::Reference => &HALFBAND_STAGE1_REFERENCE_MINIMUM_OFF_TAPS,")
    code.append("            FilterPreset::LowLatency => &HALFBAND_STAGE1_LOW_LATENCY_MINIMUM_OFF_TAPS,")
