    code.append("    match (phase, apodization) {")
    code.append("        (FilterPhase::Linear, Apodization::Off) => {")
    code.append("            HalfBandTaps::Symmetric(get_halfband_stage0_taps(preset))")
    code.append("        }")
    code.append("        (FilterPhase::Linear, Apodization::Gentle) => HalfBandTaps::General(match preset {")
    code.append("            FilterPreset::Balanced => &HALFBAND_STAGE0_BALANCED_LINEAR_GENTLE_TAPS,")
    code.append("            FilterPreset::Reference => &HALFBAND_STAGE0_REFERENCE_LINEAR_GENTLE_TAPS,")
    code.append("            FilterPreset::LowLatency => &HALFBAND_STAGE0_LOW_LATENCY_LINEAR_GENTLE_TAPS,")
    code.append("        }),")
    code.append("        (FilterPhase::Minimum, Apodization::Off) => HalfBandTaps::General(match preset {")
    code.append("            FilterPreset::Balanced => &HALFBAND_STAGE0_BALANCED_MINIMUM_OFF_TAPS,")
    code.append("            FilterPreset::Reference => &HALFBAND_STAGE0_REFERENCE_MINIMUM_OFF_TAPS,")
    code.append("            FilterPreset::LowLatency => &HALFBAND_STAGE0_LOW_LATENCY_MINIMUM_OFF_TAPS,")
