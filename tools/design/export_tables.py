#!/usr/bin/env python3
"""Export verified FIR filter and CRFB modulator coefficient tables to audigma-dsp.

Maps to Design.md §4.2, §4.3, and Plan.md Phase 1.
Generates `crates/audigma-dsp/src/tables.rs`.
"""

from pathlib import Path
import numpy as np

from design_halfband import design_all_presets
from design_src import design_polyphase_sinc
from design_crfb import synthesize_crfb


def format_f64_array(arr, indent=4, per_line=4):
    lines = []
    curr = []
    ind = " " * indent
    for val in arr:
        curr.append(f"{val:22.17e}")
        if len(curr) == per_line:
            lines.append(ind + ", ".join(curr) + ",")
            curr = []
    if curr:
        lines.append(ind + ", ".join(curr) + ",")
    return "\n".join(lines)


def generate_tables_rs(halfband, src_rational, src_asrc, crfb_rates):
    code = []
    code.append("//! Static verified filter and modulator coefficient tables (Design.md §4.2, §4.3).")
    code.append("//! Automatically generated by `tools/design/export_tables.py`.")
    code.append("//! Zero heap allocation, fully reproducible from scipy/numpy design oracles.\n")
    code.append("#![allow(clippy::excessive_precision, clippy::approx_constant)]\n")
    code.append("use crate::config::FilterPreset;")
    code.append("use crate::rates::DsdBitRateHz;\n")

    # CRFB Coefficients Struct
    code.append("/// Static 5th-order CRFB Delta-Sigma Modulator coefficient set (Design.md §4.3).")
    code.append("#[derive(Debug, Clone, Copy, PartialEq)]")
    code.append("pub struct CrfbCoefficients {")
    code.append("    /// First resonator local feedback coupling g1.")
    code.append("    pub g1: f64,")
    code.append("    /// Second resonator local feedback coupling g2.")
    code.append("    pub g2: f64,")
    code.append("    /// Quantizer DAC feedback gains a1..a5.")
    code.append("    pub a: [f64; 5],")
    code.append("    /// Input feed-in gain b1 calibrated for exact unity DC STF gain.")
    code.append("    pub b1: f64,")
    code.append("}\n")

    # Export CRFB tables
    for item in crfb_rates:
        name = item["name"].upper()
        g1 = item["g1"]
        g2 = item["g2"]
        b1 = item["b1"]
        a_formatted = ", ".join(f"{v:.17e}" for v in item["a"])
        code.append(f"/// 5th-order CRFB coefficients for {item['name']} (f_bit={item['f_bit_hz']} Hz, OSR={item['osr']:.2f}).")
        code.append(f"pub const CRFB_{name}: CrfbCoefficients = CrfbCoefficients {{")
        code.append(f"    g1: {g1:.17e},")
        code.append(f"    g2: {g2:.17e},")
        code.append(f"    a: [{a_formatted}],")
        code.append(f"    b1: {b1:.17e},")
        code.append("};\n")

    # CRFB lookup function
    code.append("/// Looks up the precomputed 5th-order CRFB coefficients for a given DSD bit rate.")
    code.append("pub fn get_crfb_coefficients(bit_rate: DsdBitRateHz) -> Option<&'static CrfbCoefficients> {")
    code.append("    match bit_rate {")
    for item in crfb_rates:
        name = item["name"].upper()
        if name.endswith("_48"):
            base = name.replace("_48", "")
            code.append(f"        DsdBitRateHz::{base}_48 => Some(&CRFB_{name}),")
        else:
            code.append(f"        DsdBitRateHz::{name} => Some(&CRFB_{name}),")
    code.append("        _ => None,")
    code.append("    }")
    code.append("}\n")

    # Export Half-band Stage 0
    s0 = halfband["stage0"]
    for preset_name, res in s0.items():
        ident = preset_name.upper()
        taps = res["unique_odd_taps"]
        code.append(f"/// Half-band Stage 0 unique odd taps for `{preset_name}` (length {res['numtaps']} taps, stopband rejection >= {res['sb_rejection_db']:.1f} dB).")
        code.append(f"pub const HALFBAND_STAGE0_{ident}_ODD_TAPS: [f64; {len(taps)}] = [")
        code.append(format_f64_array(taps, indent=4))
        code.append("];\n")

    # Export Half-band Stage 1+
    s1 = halfband["stage1"]
    for preset_name, res in s1.items():
        ident = preset_name.upper()
        taps = res["unique_odd_taps"]
        code.append(f"/// Half-band Stage 1+ unique odd taps for `{preset_name}` (length {res['numtaps']} taps, stopband rejection >= {res['sb_rejection_db']:.1f} dB).")
        code.append(f"pub const HALFBAND_STAGE1_{ident}_ODD_TAPS: [f64; {len(taps)}] = [")
        code.append(format_f64_array(taps, indent=4))
        code.append("];\n")

    # Half-band lookup functions
    code.append("/// Returns the Stage 0 half-band unique positive odd taps for a given preset.")
    code.append("pub fn get_halfband_stage0_taps(preset: FilterPreset) -> &'static [f64] {")
    code.append("    match preset {")
    code.append("        FilterPreset::Balanced => &HALFBAND_STAGE0_BALANCED_ODD_TAPS,")
    code.append("        FilterPreset::Reference => &HALFBAND_STAGE0_REFERENCE_ODD_TAPS,")
    code.append("        FilterPreset::LowLatency => &HALFBAND_STAGE0_LOW_LATENCY_ODD_TAPS,")
    code.append("    }")
    code.append("}\n")

    code.append("/// Returns the Stage 1+ half-band unique positive odd taps for a given preset.")
    code.append("pub fn get_halfband_stage1_taps(preset: FilterPreset) -> &'static [f64] {")
    code.append("    match preset {")
    code.append("        FilterPreset::Balanced => &HALFBAND_STAGE1_BALANCED_ODD_TAPS,")
    code.append("        FilterPreset::Reference => &HALFBAND_STAGE1_REFERENCE_ODD_TAPS,")
    code.append("        FilterPreset::LowLatency => &HALFBAND_STAGE1_LOW_LATENCY_ODD_TAPS,")
    code.append("    }")
    code.append("}\n")

    # Export Polyphase Rational SRC table (160 phases for 44.1k <-> 48k)
    num_p = src_rational["num_phases"]
    taps_p = src_rational["taps_per_phase"]
    code.append(f"/// Polyphase rational SRC table for cross-family conversions (44.1k <-> 48k: {num_p} phases, {taps_p} taps/phase, rejection >= {src_rational['sb_rejection_db']:.1f} dB).")
    code.append(f"pub static SRC_RATIONAL_160_PHASES: [[f64; {taps_p}]; {num_p}] = [")
    for phase in src_rational["table"]:
        code.append("    [")
        code.append(format_f64_array(phase, indent=8))
        code.append("    ],")
    code.append("];\n")

    # Export Polyphase ASRC table (256 phases for continuous drift tracking)
    num_asrc = src_asrc["num_phases"]
    taps_asrc = src_asrc["taps_per_phase"]
    code.append(f"/// Polyphase ASRC table for continuous clock drift tracking ({num_asrc} phases, {taps_asrc} taps/phase, rejection >= {src_asrc['sb_rejection_db']:.1f} dB).")
    code.append(f"pub static SRC_ASRC_256_PHASES: [[f64; {taps_asrc}]; {num_asrc}] = [")
    for phase in src_asrc["table"]:
        code.append("    [")
        code.append(format_f64_array(phase, indent=8))
        code.append("    ],")
    code.append("];\n")

    code.append("""#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_crfb_coefficient_lookups() {
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD64).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD128).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD256).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD64_48).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD128_48).is_some());
        assert!(get_crfb_coefficients(DsdBitRateHz::DSD256_48).is_some());

        let dsd256 = get_crfb_coefficients(DsdBitRateHz::DSD256).unwrap();
        assert!(dsd256.g1 > 0.0);
        assert!(dsd256.g2 > 0.0);
        assert!(dsd256.b1 > 0.0);
        assert_eq!(dsd256.a.len(), 5);
        for &a_val in &dsd256.a {
            assert!(a_val > 0.0);
        }
    }

    #[test]
    fn test_halfband_taps_lookup_and_symmetry() {
        let s0_bal = get_halfband_stage0_taps(FilterPreset::Balanced);
        assert_eq!(s0_bal.len(), 44);
        let s0_ref = get_halfband_stage0_taps(FilterPreset::Reference);
        assert_eq!(s0_ref.len(), 50);
        let s0_ll = get_halfband_stage0_taps(FilterPreset::LowLatency);
        assert_eq!(s0_ll.len(), 35);

        let s1_bal = get_halfband_stage1_taps(FilterPreset::Balanced);
        assert_eq!(s1_bal.len(), 7);
        let s1_ref = get_halfband_stage1_taps(FilterPreset::Reference);
        assert_eq!(s1_ref.len(), 8);
        let s1_ll = get_halfband_stage1_taps(FilterPreset::LowLatency);
        assert_eq!(s1_ll.len(), 6);

        let odd_sum_s1_bal: f64 = s1_bal.iter().sum::<f64>() * 2.0;
        assert!((odd_sum_s1_bal - 0.5).abs() < 1e-6);

        let odd_sum_s0_ref: f64 = s0_ref.iter().sum::<f64>() * 2.0;
        assert!((odd_sum_s0_ref - 0.5).abs() < 1e-6);
    }

    #[test]
    fn test_src_rational_table_properties() {
        assert_eq!(SRC_RATIONAL_160_PHASES.len(), 160);
        assert_eq!(SRC_RATIONAL_160_PHASES[0].len(), 48);
        for (idx, phase) in SRC_RATIONAL_160_PHASES.iter().enumerate() {
            let sum: f64 = phase.iter().sum();
            assert!(
                (sum - 1.0).abs() < 1e-6,
                "Phase {idx} sum = {sum} deviates from 1.0"
            );
        }
    }

    #[test]
    fn test_src_asrc_table_properties() {
        assert_eq!(SRC_ASRC_256_PHASES.len(), 256);
        assert_eq!(SRC_ASRC_256_PHASES[0].len(), 48);
        for (idx, phase) in SRC_ASRC_256_PHASES.iter().enumerate() {
            let sum: f64 = phase.iter().sum();
            assert!(
                (sum - 1.0).abs() < 1e-6,
                "ASRC Phase {idx} sum = {sum} deviates from 1.0"
            );
        }
    }
}
""")

    return "\n".join(code)


def main():
    print("Synthesizing Half-Band Filters...")
    halfband = design_all_presets()

    print("Synthesizing Rational Polyphase SRC (160 phases for 44.1k <-> 48k)...")
    src_rational = design_polyphase_sinc(num_phases=160, taps_per_phase=48, cutoff_ratio=0.4535, beta=12.5)

    print("Synthesizing ASRC Polyphase Table (256 phases)...")
    src_asrc = design_polyphase_sinc(num_phases=256, taps_per_phase=48, cutoff_ratio=0.4535, beta=12.5)

    print("Synthesizing 5th-Order CRFB Modulator Coefficients...")
    crfb_rates = []
    for name, f_bit in [
        ("DSD64", 2822400),
        ("DSD128", 5644800),
        ("DSD256", 11289600),
        ("DSD64_48", 3072000),
        ("DSD128_48", 6144000),
        ("DSD256_48", 12288000),
    ]:
        crfb_rates.append(synthesize_crfb(f_bit, 1.40, name))

    code = generate_tables_rs(halfband, src_rational, src_asrc, crfb_rates)

    out_path = Path(__file__).resolve().parents[2] / "crates" / "audigma-dsp" / "src" / "tables.rs"
    out_path.write_text(code)
    print(f"Successfully generated {out_path} ({len(code)} bytes)")


if __name__ == "__main__":
    main()
